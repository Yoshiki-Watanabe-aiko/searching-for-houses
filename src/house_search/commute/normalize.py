"""駅名・路線名を照合するための正規化。

掲載側の表記とマスタ側の表記は**同じ関数を通してから**突き合わせる。
片側にしか掛けない正規化を足すと、その瞬間に一致しなくなる。

⚠ 市区名の ``pipeline/persist.normalize_city_key`` とは別に持つ。共通の揺れ
（ヶ/ケ）はあるが、駅名には「ノ/之/の」という固有の揺れがあり
（一ノ関 / 一之関 / 一の関）、片方の都合で変換規則を足すともう片方が壊れる。
"""

from __future__ import annotations

import re
import unicodedata

# 両側に同じ変換を掛けるため、統合しすぎない限り真の一致は壊れない。
# 逆に、別の駅どうしが同じキーになると偽の一致を生むので、
# 「表記ゆれとして実在するもの」だけを入れる。
_REPLACEMENTS = {
    "ヶ": "ケ",  # ひばりヶ丘 / ひばりケ丘（市区名でも同じ事故があった → 鎌ケ谷）
    "ヵ": "カ",
    "之": "ノ",  # 一之関 / 一ノ関 / 一の関
    "の": "ノ",
}

# 空白（半角・全角）とナカグロ・ハイフン類。駅名の途中に入ることがある。
_STRIP_CHARS = re.compile(r"[\s　・\-‐‑‒–—―ー]+")

# 末尾の「駅」。掲載側は「上溝駅」、マスタは「上溝」と表記が割れる。
_TRAILING_STATION = re.compile(r"駅$")

# 副名称。マスタ側に付いていることがあり、掲載側には基本的に付かない
# （「押上〈スカイツリー前〉」「明治神宮前〈原宿〉」「成田空港（第１旅客ターミナル）」）。
# NFKC 後は全角丸括弧が半角になる一方、山括弧はそのまま残る。
_SUBNAME = re.compile(r"[〈(][^〉)]{0,24}[〉)]")


def normalize_key(text: str) -> str:
    """駅名・路線名の照合キーを作る。

    NFKC で全角ＪＲ・全角数字を潰し、表記ゆれを吸収し、区切り文字を落として
    小文字化する。末尾の「駅」も落とすので、掲載側の「上溝駅」とマスタの
    「上溝」が一致する。

    副名称（「押上〈スカイツリー前〉」の〈〉部分）も落とす。マスタ側にだけ付いており、
    残すと掲載側の「押上駅」と一致しない。

    ⚠ ハイフン・長音を落とすのは意図的である。「JR相模線」と「ＪＲ相模線」、
    「センター北」と「センタ-北」のような揺れを吸収するため。落とした結果
    別の駅と衝突する例は1都3県の実データでは無かった。
    """
    value = unicodedata.normalize("NFKC", text)
    value = _SUBNAME.sub("", value)
    for src, dst in _REPLACEMENTS.items():
        value = value.replace(src, dst)
    value = _TRAILING_STATION.sub("", value)
    value = _STRIP_CHARS.sub("", value)
    return value.casefold()
